import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.env.BASE_URL || 'http://localhost:5173/';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(base);
await page.getByTestId('create-something').click();
await page.getByTestId('type-game').click();
await page.getByTestId('template-game-click-target').click();
await page.getByTestId('start-creating').click();
await page.waitForSelector('.blocklySvg', { timeout: 15000 });
await page.waitForTimeout(800);
await page.screenshot({ path: 'tests/e2e/screenshots/editor.png' });
console.log('blocks:', await page.locator('.blocklyDraggable').count());
await page.getByTestId('play').click();
await page.waitForTimeout(1500);
const frame = page.frameLocator('[data-testid=preview-frame]');
console.log('score text:', await frame.locator('#score').textContent());
await frame.locator('#target').click({ force: true });
await page.waitForTimeout(300);
console.log('score after click:', await frame.locator('#score').textContent());
await page.screenshot({ path: 'tests/e2e/screenshots/playing.png' });
console.log('errors:', errors);
await browser.close();
